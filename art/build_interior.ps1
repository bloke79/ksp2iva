<#
.SYNOPSIS
  Art pipeline for one generated interior: name plate -> texture set -> Blender model -> preview renders [-> export].
.EXAMPLE
  .\art\build_interior.ps1 -Pod pod_1v_conical_crew              # model + previews (for review)
  .\art\build_interior.ps1 -Pod pod_1v_conical_crew -Export      # also FBX + materials.json into Unity/Assets/IVA/Interiors/<Interior>
.NOTES
  Intermediates go to the workspace scratch\iva-redux\<pod>\. Needs Blender 5.2 and the tools venv (Pillow).
  Shared textures come from Unity/Assets/IVA/Interiors/Shared/Textures (generated by texgen.py).
#>
param(
    [Parameter(Mandatory)][string]$Pod,
    [string]$Generator = 'model_capsule.py',
    [int]$Width = 1280,
    [int]$Samples = 64,
    [switch]$Export
)
# Blender and Python write warnings to stderr; 'Stop' would turn those into terminating errors.
# Each step checks its own output instead.
$ErrorActionPreference = 'Continue'
$art = $PSScriptRoot
$proj = Split-Path $art -Parent
$blender = 'C:\Program Files\Blender Foundation\Blender 5.2\blender.exe'
$py = 'C:\Games\KSP2Mods\tools\venv\Scripts\python.exe'
$specPath = Join-Path $art "pods\$Pod.json"
$spec = Get-Content $specPath -Raw | ConvertFrom-Json
$work = Join-Path (Split-Path (Split-Path $proj -Parent) -Parent) "scratch\iva-redux\$Pod"
$tex = Join-Path $work 'textures'
New-Item -ItemType Directory -Force $tex | Out-Null

# 1. texture set: shared textures + this pod's name plate
$shared = Join-Path $proj 'Unity\Assets\IVA\Interiors\Shared\Textures'
Copy-Item "$shared\*.png" $tex -Force
if ($spec.generator) { $Generator = $spec.generator }
if ($spec.texgen) { & $py -I (Join-Path $art $spec.texgen) $tex | ForEach-Object { "  $_" } }
$title = if ($spec.plate) { $spec.plate.title } else { ($spec.name -replace '\s*\(.*\)', '').ToUpper() + ' COMMAND POD' }
$sub = if ($spec.plate) { $spec.plate.subtitle } else { "CREW $($spec.seats)   |   MAX 9 G   |   KEEP HATCH CLEAR" }
& $py -I (Join-Path $art 'plategen.py') (Join-Path $tex 'plate.png') $title $sub | Out-Null

# 2. model
$blend = Join-Path $work "$Pod.blend"
& $blender -b --python (Join-Path $art $Generator) -- $specPath $tex $blend 2>&1 | Select-String 'couch|WARNING|Error|Traceback|objects' | ForEach-Object { $_.Line.Trim() }
if (-not (Test-Path $blend)) { throw "Model build failed" }

# 3. previews
& $blender -b --python (Join-Path $art 'render_interior.py') -- $blend $specPath (Join-Path $work 'renders') $Width $Samples 2>&1 | Select-String 'rendered|Error|Traceback' | ForEach-Object { $_.Line.Trim() }

# 4. export for Unity
if ($Export) {
    $dest = Join-Path $proj "Unity\Assets\IVA\Interiors\$($spec.interior -replace 'Interior$','')"
    & $blender -b --python (Join-Path $art 'export_interior.py') -- $blend $dest $specPath 2>&1 | Select-String 'total triangles|materials|exported|Error|Traceback' | ForEach-Object { $_.Line.Trim() }
    # pod-specific textures only: the plate plus anything this pod's texgen made that isn't in Shared
    New-Item -ItemType Directory -Force (Join-Path $dest 'Textures') | Out-Null
    Get-ChildItem $tex -Filter *.png | Where-Object { $_.Name -eq 'plate.png' -or -not (Test-Path (Join-Path $shared $_.Name)) } |
        ForEach-Object { Copy-Item $_.FullName (Join-Path $dest "Textures\$($_.Name)") -Force }
    Remove-Item (Join-Path $dest "*_export.blend*") -ErrorAction SilentlyContinue
    Write-Host "Exported to $dest"
}
Write-Host "Renders: $(Join-Path $work 'renders')"
